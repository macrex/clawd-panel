// Fonte DejaVu Sans ~7pt no formato GFXfont, para a linha do dia (pagina do
// Clawd). E a UNICA fonte proporcional do firmware: todo o resto usa a grade
// embutida do Arduino_GFX.
//
// Origem: DejaVuSans.ttf, rasterizada em MONO com hinting pelo FreeType e
// convertida para o formato de bitmap do Adafruit_GFX. A licenca da DejaVu
// permite embutir; a Arial, que seria metricamente igual a FreeSans que saiu
// daqui, nao permite — por isso a familia mudou junto com o tamanho.
//
// MENOR que a FreeSans 9pt que ela substitui: caixa de linha 17 px contra 22,
// e a frase no pior caso mede 364 px contra 423, dentro dos 452 uteis. A
// margem deixou de ser apertada, entao o corte progressivo da frase virou rede
// de seguranca em vez de rotina.
//
// A DejaVu foi desenhada para TELA em corpo pequeno, com altura-x alta e
// contraformas abertas. Encolher uma Helvetica de origem impressa fecha os
// olhais e embola o texto justamente no tamanho em que este painel e lido de
// longe — foi o que motivou trocar de familia em vez de so achar um numero
// menor.
//
// Empacotamento: 1 bit por pixel, MSB primeiro, linhas continuas dentro do
// glifo, cada glifo alinhado a byte no fim.
//
// USO: `g->setFont(&DejaVuSans7pt7b)` e — obrigatorio — `g->setFont()` para
// voltar a embutida. Com fonte GFX o cursor Y e a LINHA DE BASE.

